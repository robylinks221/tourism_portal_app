  static WorldCountry? byName(String? countryName) {
    final target = countryName?.trim().toLowerCase();
    if (target == null || target.isEmpty) return null;

    for (final country in all) {
      if (country.name.toLowerCase() == target) return country;
    }
    return null;
  }

  static WorldCountry? byCode(String? countryCode) {
    final target = countryCode?.trim().toUpperCase();
    if (target == null || target.isEmpty) return null;

    for (final country in all) {
      if (country.code == target) return country;
    }
    return null;
  }

  static bool isSupported(String? countryName) => byName(countryName) != null;

  static String flagUrlForCountry(String? countryName) =>
      byName(countryName)?.flagUrl ?? '';
